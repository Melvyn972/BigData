create extension if not exists btree_gist;

drop table if exists promo_code_usages, promo_codes, promotion_products, promotion_categories,
  promotions, order_items, orders, cart_items, carts, price_history, currencies,
  product_variants, product_categories, products, brands, categories, addresses, users cascade;
drop type if exists address_type, order_status, promotion_scope cascade;
drop function if exists price_at(bigint, char, timestamptz);
drop function if exists set_updated_at() cascade;

create type address_type    as enum ('home', 'work', 'other');
create type order_status    as enum ('pending', 'paid', 'shipped', 'delivered', 'cancelled');
create type promotion_scope as enum ('order', 'product', 'category');

create table users (
  user_id       bigint generated by default as identity primary key,
  last_name     varchar(100),
  first_name    varchar(100),
  display_name  varchar(100),
  email         varchar(255) not null,
  phone         varchar(20),
  password_hash varchar(255) not null,
  created_at    timestamptz  not null default now(),
  is_active     boolean      not null default true
);

create unique index users_email_uq on users (lower(email));

create table addresses (
  address_id      bigint generated by default as identity primary key,
  user_id         bigint not null references users (user_id) on delete cascade,
  type            address_type not null default 'home',
  label           varchar(100),
  street          varchar(255) not null,
  additional_info varchar(255),
  postal_code     varchar(10)  not null,
  city            varchar(100) not null,
  country         varchar(100) not null
);
create index addresses_user_idx on addresses (user_id);

create table categories (
  category_id        bigint generated by default as identity primary key,
  name               varchar(100) not null,
  parent_category_id bigint references categories (category_id) on delete restrict,
  constraint categories_not_own_parent check (parent_category_id <> category_id)
);
create index categories_parent_idx on categories (parent_category_id);

create table brands (
  brand_id bigint generated by default as identity primary key,
  name     varchar(100) not null unique
);

create table products (
  product_id  bigint generated by default as identity primary key,
  brand_id    bigint not null references brands (brand_id) on delete restrict,
  name        varchar(150) not null,
  description text
);
create index products_brand_idx on products (brand_id);

create table product_categories (
  product_id  bigint not null references products (product_id) on delete cascade,
  category_id bigint not null references categories (category_id) on delete cascade,
  primary key (product_id, category_id)
);
create index product_categories_category_idx on product_categories (category_id);

create table product_variants (
  variant_id bigint generated by default as identity primary key,
  product_id bigint not null references products (product_id) on delete restrict,
  reference  varchar(50) not null unique,
  color      varchar(50),
  size       varchar(20),
  constraint product_variants_combo_uq unique nulls not distinct (product_id, color, size)
);

create table currencies (
  currency_code char(3) primary key check (currency_code = upper(currency_code)),
  name          varchar(50) not null,
  symbol        varchar(5)
);

create table price_history (
  price_id      bigint generated by default as identity primary key,
  variant_id    bigint not null references product_variants (variant_id) on delete restrict,
  currency_code char(3) not null references currencies (currency_code),
  amount        numeric(10,2) not null check (amount >= 0),
  valid_from    timestamptz not null,
  valid_to      timestamptz,
  constraint price_history_dates_ck check (valid_to is null or valid_to > valid_from),
  constraint price_history_start_uq unique (variant_id, currency_code, valid_from),

  constraint price_history_no_overlap exclude using gist (
    variant_id with =, currency_code with =, tstzrange(valid_from, valid_to) with &&
  )
);

create table carts (
  cart_id    bigint generated by default as identity primary key,
  user_id    bigint not null unique references users (user_id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);

create table cart_items (
  cart_id    bigint not null references carts (cart_id) on delete cascade,
  variant_id bigint not null references product_variants (variant_id) on delete cascade,
  quantity   integer not null check (quantity > 0),
  primary key (cart_id, variant_id)
);

create table orders (
  order_id                 bigint generated by default as identity primary key,
  public_id                varchar(20) not null unique,
  user_id                  bigint references users (user_id) on delete set null,
  ordered_at               timestamptz not null default now(),
  status                   order_status not null default 'pending',
  currency_code            char(3) not null references currencies (currency_code),
  total_paid               numeric(10,2) not null check (total_paid >= 0),

  customer_email           varchar(255) not null,
  customer_first_name      varchar(100) not null,
  customer_last_name       varchar(100) not null,
  customer_phone           varchar(20),

  shipping_street          varchar(255) not null,
  shipping_additional_info varchar(255),
  shipping_postal_code     varchar(10)  not null,
  shipping_city            varchar(100) not null,
  shipping_country         varchar(100) not null
);
create index orders_user_idx on orders (user_id);

create table order_items (
  order_id        bigint not null references orders (order_id) on delete cascade,
  variant_id      bigint not null references product_variants (variant_id) on delete restrict,
  quantity        integer not null check (quantity > 0),
  unit_price_paid numeric(10,2) not null check (unit_price_paid >= 0),
  primary key (order_id, variant_id)
);

create table promotions (
  promotion_id     bigint generated by default as identity primary key,
  name             varchar(100) not null,
  discount_percent numeric(5,2) not null check (discount_percent > 0 and discount_percent <= 100),
  scope            promotion_scope not null,
  valid_from       timestamptz not null,
  valid_to         timestamptz not null,
  max_uses         integer check (max_uses > 0),
  constraint promotions_dates_ck check (valid_to > valid_from),
  constraint promotions_id_scope_uq unique (promotion_id, scope)
);

create table promotion_products (
  promotion_id bigint not null,
  product_id   bigint not null references products (product_id) on delete cascade,
  scope        promotion_scope not null default 'product' check (scope = 'product'),
  primary key (promotion_id, product_id),
  foreign key (promotion_id, scope) references promotions (promotion_id, scope)
    on delete cascade on update cascade
);

create table promotion_categories (
  promotion_id bigint not null,
  category_id  bigint not null references categories (category_id) on delete cascade,
  scope        promotion_scope not null default 'category' check (scope = 'category'),
  primary key (promotion_id, category_id),
  foreign key (promotion_id, scope) references promotions (promotion_id, scope)
    on delete cascade on update cascade
);

create table promo_codes (
  promo_code_id        bigint generated by default as identity primary key,
  code                 varchar(50) not null unique,
  promotion_id         bigint not null references promotions (promotion_id) on delete cascade,
  reserved_user_id     bigint references users (user_id) on delete cascade,
  max_uses             integer check (max_uses > 0),
  one_use_per_customer boolean not null default false,
  constraint promo_codes_id_once_uq unique (promo_code_id, one_use_per_customer)
);
create index promo_codes_promotion_idx on promo_codes (promotion_id);

create table promo_code_usages (
  usage_id             bigint generated by default as identity primary key,
  promo_code_id        bigint not null,
  order_id             bigint not null unique references orders (order_id) on delete cascade,
  user_id              bigint references users (user_id) on delete set null,
  customer_email       varchar(255) not null,
  one_use_per_customer boolean not null,
  discount_amount      numeric(10,2) not null check (discount_amount >= 0),
  used_at              timestamptz not null default now(),
  foreign key (promo_code_id, one_use_per_customer)
    references promo_codes (promo_code_id, one_use_per_customer) on update cascade
);

create unique index promo_code_usages_once_per_customer_uq
  on promo_code_usages (promo_code_id, lower(customer_email))
  where one_use_per_customer;

create function price_at(p_variant_id bigint, p_currency char(3), p_at timestamptz default now())
returns numeric language sql stable as $$
  select amount from price_history
  where variant_id = p_variant_id and currency_code = p_currency
    and valid_from <= p_at and (valid_to is null or valid_to > p_at)
$$;

create function set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
create trigger carts_set_updated_at before update on carts
  for each row execute function set_updated_at();
